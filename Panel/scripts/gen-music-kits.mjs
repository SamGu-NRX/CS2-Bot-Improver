// Regenerates src/data/musicKits.ts from BotRandomizer's cosmetic_catalog.json.
// Usage: node scripts/gen-music-kits.mjs <path to cosmetic_catalog.json>
// The catalog needs `musicKits` (definition IDs) and `musicKitNames` (ID -> English name).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const catalogPath = process.argv[2];
if (!catalogPath) {
  console.error("usage: node scripts/gen-music-kits.mjs <cosmetic_catalog.json>");
  process.exit(1);
}

const catalog = JSON.parse(readFileSync(catalogPath, "utf8"));
const { musicKits, musicKitNames, source } = catalog;
if (!Array.isArray(musicKits) || typeof musicKitNames !== "object" || musicKitNames === null) {
  console.error("catalog is missing `musicKits` (array) or `musicKitNames` (object)");
  process.exit(1);
}

const PREFIX = "Music Kit | ";
const kits = musicKits.map((id) => {
  const full = musicKitNames[String(id)];
  if (typeof full !== "string") {
    console.error(`music kit ${id} has no entry in musicKitNames`);
    process.exit(1);
  }
  return { id, name: full.startsWith(PREFIX) ? full.slice(PREFIX.length) : full };
});

const origin = source?.package
  ? `${source.package}@${source.version} (${source.repository}@${String(source.commit).slice(0, 12)})`
  : "unknown source";

const lines = [
  "// GENERATED by scripts/gen-music-kits.mjs from BotRandomizer's cosmetic_catalog.json",
  `// (keys musicKits and musicKitNames; catalog built from ${origin}).`,
  "// Do not edit by hand: rerun the script against a newer catalog when Valve adds kits.",
  "// `id` is the music kit definition index that br_player_music_kit accepts.",
  "",
  "export type MusicKit = { id: number; name: string };",
  "",
  "export const MUSIC_KITS: readonly MusicKit[] = [",
  ...kits.map((k) => `  { id: ${k.id}, name: ${JSON.stringify(k.name)} },`),
  "];",
  "",
];

const out = fileURLToPath(new URL("../src/data/musicKits.ts", import.meta.url));
writeFileSync(out, lines.join("\n"));
console.log(`wrote ${kits.length} kits to ${out}`);
